<?php

declare(strict_types=1);

namespace App\Database;

use PDO;

/**
 * Контракт миграции.
 *
 * Каждая миграция - отдельный класс, реализующий два метода:
 * up() применяет изменения, down() откатывает их.
 *
 * Файлы миграций лежат в database/migrations/ с именами вида
 * 2026_09_30_000001_create_categories_table.php. Так как имя файла
 * не совпадает с именем класса (нужен префикс-таймстамп для сортировки),
 * эти файлы подключены через classmap в composer.json, а не через PSR-4.
 * Namespace классов - Database\Migrations (см. classmap).
 *
 * Почему не PSR-4: он требует точного совпадения имени файла с именем
 * класса (CreateCategoriesTable.php). Тогда порядок применения зависел бы
 * от лексикографической сортировки имён, и добавление миграции "в середину"
 * истории сломало бы порядок. Таймстамп-префикс фиксирует порядок навсегда.
 */
interface Migration
{
    /**
     * Применяет миграцию: создаёт таблицы, индексы, внешние ключи.
     *
     * @param PDO $pdo Активное соединение с БД
     */
    public function up(PDO $pdo): void;

    /**
     * Откатывает миграцию: удаляет всё, что создал up().
     *
     * @param PDO $pdo Активное соединение с БД
     */
    public function down(PDO $pdo): void;
}
